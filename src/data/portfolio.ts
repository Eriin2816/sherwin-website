const VIDEO_DIR = '/videos/portfolio'

function portfolioVideo(
  slug: string,
  orientation: ProjectVideo['orientation'],
  duration: number,
  hasAudio = true
): ProjectVideo {
  return {
    src: `${VIDEO_DIR}/${slug}.mp4`,
    poster: `${VIDEO_DIR}/posters/${slug}.webp`,
    orientation,
    duration,
    hasAudio,
  }
}

