export interface Project {
  id: string
  title: string
  subtitle: string
  description: string
  impact: string
  tech: string[]
  category: string
  /** Filter tab ids this project appears under (see projectFilters) */
  filters: string[]
  /** Flagship full applications render one-per-row instead of in the 3-up grid. */
  type?: 'saas'
  /** Optional "Key Platform Capabilities" block in the case study. */
  capabilities?: string[]
  featured?: boolean
  image?: string
  /** Optional multi-screenshot workflow, shown as an auto-advancing slider. Takes precedence over `image`. */
  images?: string[]
  /**
   * How the screenshot fills its 16:9 frame, applied identically on the card and
   * the case-study hero. `contain` shows the whole interface (letterboxed against
   * the card background); `cover` fills the frame and may crop the edges.
   */
  imageFit?: 'cover' | 'contain'
  /** Video showcase. Takes precedence over images; always framed 4:3 on card and modal. */
  video?: ProjectVideo
  highlights?: string[]
  problem: string
  solution: string[]
  outcome: string[]
}

export interface ProjectVideo {
  /** Compressed H.264 file under /public (see public/videos/portfolio). */
  src: string
  poster: string
  /** Source aspect. Both are letterboxed into the same 4:3 frame. */
  orientation: 'portrait' | 'landscape'
  /** Length in seconds, shown before playback so no video bytes are fetched up front. */
  duration: number
  /** Screen recordings ship without an audio track, so they get no mute toggle. */
  hasAudio: boolean
}

